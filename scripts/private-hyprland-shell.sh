#!/usr/bin/env bash
# Run a command inside a private nested Hyprland session: its own 0700 runtime directory, session
# bus, accessibility bus, a virtual kwin_wayland host compositor and a Hyprland instance rendering
# into it. Nothing here touches the owner's desktop, bus or accessibility registry: every variable
# that could point at them is removed before the first child starts, and the compositor pair
# serves sockets that exist only inside the runtime directory.
# Usage: scripts/private-hyprland-shell.sh [--size WxH] -- command [args...]
#
# The command runs with XDG_RUNTIME_DIR, DBUS_SESSION_BUS_ADDRESS, WAYLAND_DISPLAY and
# HYPRLAND_INSTANCE_SIGNATURE naming the private session. It is not run until the compositor
# answers its IPC with no configuration errors and the AT-SPI registry answers on the private
# accessibility bus.
#
# The seat gets one virtual pointer for the whole session (private_hyprland_seat_pointer.py),
# because a real desktop always has a mouse and the host compositor offers none. Writing
# "move X Y WIDTH HEIGHT" to <runtime dir>/seat-pointer.fifo moves it with real motion events.
#
# Hyprland's IPC sockets live under <runtime dir>/hypr/<signature>/ and a Unix socket path holds at
# most 107 bytes, so the runtime directory must stay short: the default base is /tmp/adh-<uid>,
# not the longer base private-session.sh uses.
set -euo pipefail
umask 077

size=1280x800
while [ $# -gt 0 ]; do
  case "$1" in
    --size) size=${2:?--size needs WxH}; shift 2 ;;
    --) shift; break ;;
    *) break ;;
  esac
done
if [ $# -eq 0 ]; then
  echo "usage: private-hyprland-shell.sh [--size WxH] -- command [args...]" >&2
  exit 2
fi
case "$size" in
  [0-9]*x[0-9]*) ;;
  *) echo "private-hyprland-shell: --size needs WxH, got $size" >&2; exit 2 ;;
esac
width=${size%x*}
height=${size#*x}

registryd=
for candidate in /usr/lib/at-spi2-registryd /usr/libexec/at-spi2-registryd /usr/lib/at-spi2-core/at-spi2-registryd; do
  [ -x "$candidate" ] && { registryd=$candidate; break; }
done
for tool in Hyprland hyprctl kwin_wayland dbus-daemon dbus-update-activation-environment gdbus setsid; do
  command -v "$tool" > /dev/null || { echo "private-hyprland-shell: missing tool: $tool" >&2; exit 1; }
done
[ -n "$registryd" ] || { echo "private-hyprland-shell: missing at-spi2-registryd" >&2; exit 1; }

base=${AGENT_DESKTOP_SESSION_BASE:-/tmp/adh-$(id -u)}
export AGENT_DESKTOP_SESSION_BASE=$base
mkdir -p "$base"
chmod 700 "$base"
rt=$(mktemp -d "$base/rt.XXXXXX")
chmod 700 "$rt"
if [ "${#rt}" -gt 26 ]; then
  echo "private-hyprland-shell: $rt is too long for Hyprland's IPC sockets (at most 26 bytes); set AGENT_DESKTOP_SESSION_BASE to a shorter directory" >&2
  rm -rf -- "$rt"
  exit 1
fi
mkdir -p "$rt/cfg/glib-2.0/settings" "$rt/cfg/hypr" "$rt/data" "$rt/cache" "$rt/ad-home" "$rt/tmp"
printf '[org/gnome/desktop/interface]\ntoolkit-accessibility=true\nenable-animations=false\n' > "$rt/cfg/glib-2.0/settings/keyfile"
cat > "$rt/cfg/hypr/hyprland.lua" <<LUA
hl.config({ autogenerated = false })
hl.monitor({ output = "", mode = "${width}x${height}@60", position = "0x0", scale = 1 })
hl.config({
  input = { kb_layout = "us" },
  general = { gaps_in = 0, gaps_out = 0, border_size = 1 },
  decoration = { rounding = 0, shadow = { enabled = false } },
  animations = { enabled = false },
  xwayland = { enabled = false },
  misc = { disable_hyprland_logo = true, disable_splash_rendering = true },
  debug = { disable_logs = false },
})
LUA
if [ -n "${AD_RUNNER_PID:-}" ] && [ -n "${AD_RUNNER_START:-}" ]; then
  printf '%s %s\n' "$AD_RUNNER_PID" "$AD_RUNNER_START" > "$rt/harness-owner"
fi

pids=()
# shellcheck disable=SC2317,SC2329
process_start() {
  local stat fields
  stat=$(cat "${2:-/proc}/$1/stat" 2>/dev/null) || return 1
  stat=${stat##*) }
  read -r -a fields <<< "$stat"
  [ -n "${fields[19]:-}" ] || return 1
  printf '%s\n' "${fields[19]}"
}
# shellcheck disable=SC2317,SC2329
session_members() {
  local root=/proc environ pid start
  for environ in "$root"/[0-9]*/environ; do
    pid=${environ%/environ}
    pid=${pid##*/}
    [ "$pid" != "$$" ] || continue
    start=$(process_start "$pid" "$root") || continue
    if grep -qzxF "XDG_RUNTIME_DIR=$rt" "$environ" 2>/dev/null &&
       [ "$(process_start "$pid" "$root")" = "$start" ]; then
      echo "$pid $start"
    fi
  done
}
# shellcheck disable=SC2317,SC2329
session_signal() {
  local pid=$1 start=$2 sig=$3 root=${4:-/proc}
  [ "$(process_start "$pid" "$root")" = "$start" ] || return 0
  grep -qzxF "XDG_RUNTIME_DIR=$rt" "$root/$pid/environ" 2>/dev/null || return 0
  [ "$(process_start "$pid" "$root")" = "$start" ] || return 0
  kill "-$sig" "$pid" 2>/dev/null || true
}
# shellcheck disable=SC2317,SC2329
cleanup() {
  local pid start mount
  trap '' INT TERM HUP
  for pid in "${pids[@]}"; do
    kill -TERM "$pid" 2>/dev/null || true
  done
  while read -r pid start; do session_signal "$pid" "$start" TERM; done < <(session_members)
  sleep 1
  for pid in "${pids[@]}"; do
    kill -KILL "$pid" 2>/dev/null || true
  done
  while read -r pid start; do session_signal "$pid" "$start" KILL; done < <(session_members)
  for _ in $(seq 1 50); do
    [ -z "$(session_members)" ] && break
    sleep 0.1
  done
  for mount in "$rt/doc" "$rt/gvfs"; do
    fusermount3 -u "$mount" 2>/dev/null || fusermount -u "$mount" 2>/dev/null || true
  done
  case "$rt" in
    "$base"/rt.?*)
      # dms run copies its shell files into the runtime directory read-only.
      [ ! -d "$rt" ] || { chmod -R u+w -- "$rt" 2>/dev/null; rm -rf -- "$rt"; } ;;
  esac
}
trap cleanup EXIT

# AT_SPI_BUS_ADDRESS points a toolkit straight at an accessibility bus, NO_AT_BRIDGE and GTK_A11Y
# switch the bridge off, HYPRLAND_INSTANCE_SIGNATURE and WAYLAND_DISPLAY name the owner's
# compositor: any of them inherited would put an app or a query on the owner's desktop.
unset DISPLAY WAYLAND_DISPLAY XAUTHORITY DBUS_SESSION_BUS_ADDRESS AT_SPI_BUS_ADDRESS NO_AT_BRIDGE \
  GTK_A11Y HYPRLAND_INSTANCE_SIGNATURE HYPRLAND_CMD XDG_SESSION_ID XDG_SEAT XDG_VTNR \
  DBUS_STARTER_ADDRESS DBUS_STARTER_BUS_TYPE QT_QPA_PLATFORM GDK_BACKEND SWAYSOCK I3SOCK \
  XDG_ACTIVATION_TOKEN DESKTOP_STARTUP_ID NIRI_SOCKET
export XDG_RUNTIME_DIR=$rt
export XDG_CONFIG_HOME=$rt/cfg
export XDG_DATA_HOME=$rt/data
export XDG_CACHE_HOME=$rt/cache
export TMPDIR=$rt/tmp
export GSETTINGS_BACKEND=keyfile
export XDG_CURRENT_DESKTOP=Hyprland
export XDG_SESSION_DESKTOP=Hyprland
export XDG_SESSION_TYPE=wayland
export AGENT_DESKTOP_PRIVATE_SESSION=$rt
export AGENT_DESKTOP_HOME=$rt/ad-home
export HYPRLAND_NO_SD_NOTIFY=1
export HYPRLAND_NO_SD_VARS=1
export HYPRLAND_NO_CRASHREPORTER=1

bus_address="unix:path=$rt/bus"
dbus-daemon --session --nofork --address="$bus_address" 2> "$rt/bus.log" &
pids+=("$!")
export DBUS_SESSION_BUS_ADDRESS=$bus_address
for _ in $(seq 1 100); do
  [ -S "$rt/bus" ] && break
  sleep 0.1
done
[ -S "$rt/bus" ] || { echo "private-hyprland-shell: the session bus did not start" >&2; exit 1; }

dbus-update-activation-environment XDG_RUNTIME_DIR XDG_CONFIG_HOME XDG_DATA_HOME XDG_CACHE_HOME \
  TMPDIR GSETTINGS_BACKEND XDG_CURRENT_DESKTOP XDG_SESSION_DESKTOP XDG_SESSION_TYPE \
  AGENT_DESKTOP_PRIVATE_SESSION AGENT_DESKTOP_HOME

# shellcheck disable=SC2317,SC2329
fail_with_logs() {
  local name
  echo "private-hyprland-shell: $1" >&2
  for name in kwin.log hyprland.log registryd.log; do
    [ -s "$rt/$name" ] && { echo "--- $name (tail)" >&2; tail -n 20 "$rt/$name" >&2; }
  done
  exit 1
}

start_accessibility() {
  local address
  address=$(timeout 20 gdbus call --session -d org.a11y.Bus -o /org/a11y/bus -m org.a11y.Bus.GetAddress) \
    || fail_with_logs "the accessibility bus launcher did not answer"
  address=${address#*\'}
  address=${address%%\'*}
  setsid "$registryd" > "$rt/registryd.log" 2>&1 < /dev/null &
  pids+=("$!")
  for _ in $(seq 1 50); do
    if timeout 5 gdbus call --address "$address" -d org.a11y.atspi.Registry -o /org/a11y/atspi/registry \
         -m org.a11y.atspi.Registry.GetRegisteredEvents > /dev/null 2>&1; then
      return 0
    fi
    sleep 0.2
  done
  fail_with_logs "the AT-SPI registry did not answer on $address"
}

hypr_signature() {
  find "$rt/hypr" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' 2> /dev/null | head -n 1 || true
}

compositor_healthy() {
  local signature=$1 monitors errors
  [ -S "$rt/hypr/$signature/.socket.sock" ] || return 1
  monitors=$(HYPRLAND_INSTANCE_SIGNATURE=$signature timeout 5 hyprctl -j monitors 2> /dev/null || true)
  case "$monitors" in
    *'"name"'*) ;;
    *) return 1 ;;
  esac
  errors=$(HYPRLAND_INSTANCE_SIGNATURE=$signature timeout 5 hyprctl configerrors 2> /dev/null || true)
  [ -z "${errors//[$' \t\r\n']/}" ] || fail_with_logs "Hyprland reports configuration errors: $errors"
}

start_compositors() {
  local signature='' socket
  setsid kwin_wayland --virtual --width "$width" --height "$height" --socket wl-host --no-lockscreen \
    --no-global-shortcuts > "$rt/kwin.log" 2>&1 < /dev/null &
  pids+=("$!")
  for _ in $(seq 1 100); do
    [ -S "$rt/wl-host" ] && break
    sleep 0.1
  done
  [ -S "$rt/wl-host" ] || fail_with_logs "the host compositor did not create its socket"
  WAYLAND_DISPLAY=wl-host setsid Hyprland > "$rt/hyprland.log" 2>&1 < /dev/null &
  pids+=("$!")
  for _ in $(seq 1 100); do
    signature=$(hypr_signature)
    if [ -n "$signature" ] && compositor_healthy "$signature"; then
      socket=$(sed -n 2p "$rt/hypr/$signature/hyprland.lock")
      [ -S "$rt/$socket" ] || fail_with_logs "Hyprland's Wayland socket $socket is missing"
      export WAYLAND_DISPLAY=$socket
      export HYPRLAND_INSTANCE_SIGNATURE=$signature
      return 0
    fi
    sleep 0.2
  done
  fail_with_logs "Hyprland did not become healthy"
}

# The host compositor has no input devices, so the nested seat would carry a pointer only while a
# command holds a virtual one, and each command would reach the clients as a new pointer that
# enters their surfaces without leaving them. A real desktop has a mouse; this holder is that mouse,
# and "move X Y WIDTH HEIGHT" written to $rt/seat-pointer.fifo moves it the way a hand would.
start_seat_pointer() {
  local ready=''
  setsid python3 -I "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/private_hyprland_seat_pointer.py" \
    "$rt/seat-pointer.fifo" > "$rt/seat-pointer.log" 2>&1 < /dev/null &
  pids+=("$!")
  for _ in $(seq 1 50); do
    ready=$(grep -c ': ready' "$rt/seat-pointer.log" 2> /dev/null || true)
    [ "${ready:-0}" -gt 0 ] && return 0
    sleep 0.1
  done
  fail_with_logs "the seat pointer did not start: $(cat "$rt/seat-pointer.log" 2> /dev/null)"
}

start_accessibility
start_compositors
start_seat_pointer
dbus-update-activation-environment WAYLAND_DISPLAY HYPRLAND_INSTANCE_SIGNATURE

# A trap only runs once the foreground child exits, so a payload that keeps running would hold the
# whole cleanup open. The payload therefore gets its own process group and runs in the background:
# a caught signal forwards to that group at once, escalates to KILL after the grace period, and the
# EXIT sweep then reaches any member that left the group.
grace_s=${AGENT_DESKTOP_SESSION_GRACE_S:-3}
status=0
setsid -- "$@" &
payload_pid=$!

# shellcheck disable=SC2317,SC2329
signal_payload() {
  local sig="$1"
  trap '' INT TERM HUP
  kill -"$sig" -- "-$payload_pid" 2>/dev/null || true
  local deadline=$((SECONDS + grace_s))
  while kill -0 -- "-$payload_pid" 2>/dev/null && [ "$SECONDS" -lt "$deadline" ]; do
    sleep 0.1
  done
  kill -KILL -- "-$payload_pid" 2>/dev/null || true
  wait "$payload_pid" 2>/dev/null || true
  case "$sig" in
    INT) exit 130 ;;
    HUP) exit 129 ;;
    *) exit 143 ;;
  esac
}
trap 'signal_payload INT' INT
trap 'signal_payload TERM' TERM
trap 'signal_payload HUP' HUP
wait "$payload_pid" || status=$?
exit "$status"
